"""Generate missing published dialogue variants without overwriting existing voice clips.

Uses the same Edge voices and speaking rate as the original Reply Coach generator.
Only public lesson text is fetched. No student data or credentials are read.
Requires edge-tts >= 7.3.1 (the older 7.2.8 generator uses a retired service protocol).
"""
import argparse
import asyncio
import hashlib
import json
from pathlib import Path
import urllib.request
import edge_tts

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets' / 'audio' / 'reply-coach'
VOICES = {'SUMI': 'ja-JP-NanamiNeural', 'HARU': 'ja-JP-KeitaNeural'}

async def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source-url', default='https://portal.japlearn.com/api/reply-coach/chapters')
    parser.add_argument('--generate', action='store_true')
    args = parser.parse_args()
    with urllib.request.urlopen(args.source_url, timeout=60) as response:
        chapters = json.load(response)
    original = json.loads((OUT / 'manifest.json').read_text(encoding='utf-8'))
    known = {(row['text'], row['character']) for row in original if (OUT / (row['id'] + '.mp3')).is_file()}
    manifest_path = OUT / 'verified-variants.json'
    variants = json.loads(manifest_path.read_text(encoding='utf-8')) if manifest_path.exists() else []
    for row in variants:
        path = OUT / row['file']
        if path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() == row['sha256']:
            known.add((row['text'], row['character']))
    rows = []
    for chapter in chapters:
        for node in chapter.get('nodes', []):
            if node.get('japanese') and node.get('characterKey') in VOICES:
                rows.append((node['japanese'], node['characterKey']))
            rows.extend((choice['japanese'], 'SUMI') for choice in node.get('choices', []) if choice.get('japanese'))
    missing = sorted(set(rows) - known)
    print(f'{len(rows)} published spoken entries; {len(missing)} distinct missing text/voice pairs.', flush=True)
    if not args.generate:
        return
    indexed = {(row['text'], row['character']): row for row in variants}
    for text, character in missing:
        name = 'verified-' + hashlib.sha256((character + '\n' + text).encode()).hexdigest()[:16] + '.mp3'
        target = OUT / name
        if not target.exists() or target.stat().st_size < 500:
            temporary = target.with_suffix('.pending.mp3')
            for attempt in range(3):
                try:
                    await edge_tts.Communicate(text, VOICES[character], rate='-5%').save(str(temporary))
                    if temporary.stat().st_size < 500:
                        raise RuntimeError('Empty generated audio')
                    temporary.replace(target)
                    break
                except Exception:
                    if attempt == 2:
                        raise
                    await asyncio.sleep(attempt + 1)
        indexed[(text, character)] = {'text': text, 'character': character, 'voice': VOICES[character], 'file': name,
            'sha256': hashlib.sha256(target.read_bytes()).hexdigest()}
        print(f'Prepared {character}: {name}', flush=True)
    variants = list(indexed.values())
    manifest_path.write_text(json.dumps(variants, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    lines = ['// Generated by scripts/sync_reply_coach_audio.py. Match by text and character, never ID alone.', 'const variants = [']
    for row in variants:
        lines.append('  { text: ' + json.dumps(row['text'], ensure_ascii=False) + ', character: ' + json.dumps(row['character'])
            + ", asset: require('../assets/audio/reply-coach/" + row['file'] + "') },")
    lines.extend(['];', 'export default variants;', ''])
    (ROOT / 'app' / 'replyCoachVoiceVariants.ts').write_text('\n'.join(lines), encoding='utf-8')
    print(f'{len(variants)} verified voice variants mapped; original recordings retained.', flush=True)

if __name__ == '__main__':
    asyncio.run(main())
